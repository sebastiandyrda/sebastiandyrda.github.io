<script>
(function () {
  var openOverlay = null;

  window.openBibtex = function (id) {
    var overlay = document.getElementById(id);
    if (!overlay) return;
    if (openOverlay && openOverlay !== overlay) closeBibtex();
    overlay.classList.add('is-open');
    document.body.classList.add('bib-locked');
    openOverlay = overlay;
    var close = overlay.querySelector('.bib-close');
    if (close) close.focus();
  };

  window.closeBibtex = function () {
    if (!openOverlay) return;
    openOverlay.classList.remove('is-open');
    document.body.classList.remove('bib-locked');
    openOverlay = null;
  };

  function copyText(text, button) {
    function done() {
      var original = button.getAttribute('data-label') || button.textContent;
      button.setAttribute('data-label', original);
      button.textContent = 'Copied ✓';
      button.classList.add('copied');
      setTimeout(function () {
        button.textContent = original;
        button.classList.remove('copied');
      }, 1600);
    }
    if (navigator.clipboard && window.isSecureContext) {
      navigator.clipboard.writeText(text).then(done, function () { legacy(text, done); });
    } else {
      legacy(text, done);
    }
  }

  function legacy(text, done) {
    var ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    try { document.execCommand('copy'); done(); } catch (e) { /* no-op */ }
    document.body.removeChild(ta);
  }

  document.addEventListener('click', function (e) {
    var target = e.target;
    if (target.classList.contains('bib-overlay')) { closeBibtex(); return; }
    if (target.classList.contains('bib-close')) { closeBibtex(); return; }
    if (target.classList.contains('bib-copy')) {
      var card = target.closest('.bib-card');
      if (card) copyText(card.querySelector('.bib-code').textContent, target);
    }
  });

  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' || e.keyCode === 27) closeBibtex();
  });
})();
</script>
